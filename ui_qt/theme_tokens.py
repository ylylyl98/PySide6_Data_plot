"""Shared semantic colors for native Quick and the legacy Widgets frontend.

This module deliberately imports no Qt UI classes.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from types import MappingProxyType


@lru_cache(maxsize=2)
def resolved_aliases(mode: str):
    """Resolve the same semantic palette without importing a Widgets manager."""
    from ui_qt.fluent_ui.tokens import TokenRepository
    root = Path(__file__).resolve().parent / "fluent_ui" / "resources"
    repository = TokenRepository(root / "fluent2-official-web-theme-tokens.json",
                                 root / "qt-token-map.json", root / "shell-token-map.json")
    resolved = repository.resolve(mode, shell_profile="fluent-workbench")
    return MappingProxyType({**resolved.aliases, **PROJECT_ALIASES.get(mode, {})})

