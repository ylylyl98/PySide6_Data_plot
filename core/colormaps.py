def resolve_cmap(value: str, default: str) -> str:
    """Resolve a display label, stable ID, or legacy standard name.

    Returns the stable Matplotlib colormap name for known inputs; otherwise
    returns ``default``.
    """
    text = str(value).strip()
    if text in _LABEL_TO_ID:
        return _LABEL_TO_ID[text]
    if text in _CUSTOM_IDS or text in STANDARD_COLORMAPS:
        return text
    return default


def register_colormaps() -> None:
    """Register the custom colormaps with Matplotlib (idempotent)."""
    registry = matplotlib.colormaps
    for cmap_id, rgb in _CUSTOM_RGB:
        if cmap_id in registry:
            continue
        colors = [(r / 255.0, g / 255.0, b / 255.0) for r, g, b in rgb]
        registry.register(ListedColormap(colors, name=cmap_id))
